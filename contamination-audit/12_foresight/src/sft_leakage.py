# -*- coding: utf-8 -*-
"""Extract verbatim leakage from the 1913 model's own SFT data. The instruct data is self-generated (response_model =
Ranke-4B-1913), so any post-1913 fact stated as HISTORY in a response is the base model's pretraining contamination
surfacing in plain text. We scan for post-cutoff markers (the Great War, 1914-1918, Versailles, ...), pull the sentence
and its seed question, and split predictions ("will / is coming") from facts stated in the past tense (the real leak).
Saves results/superlatives/sft_leakage_examples.html + .txt.  Run:  python src/sft_leakage.py
"""
import os, re, html, json
from datasets import load_dataset
import common

OUT = os.path.join(common.RESULTS, "superlatives")
DATASETS = ["ranke-1913-sft-dataset", "ranke-1913-sft-seedresponses"]
PRED = re.compile(r"\b(will|shall|would|is coming|to come|expected|prophec|predict|future|near future|some day|one day)\b", re.I)
# WWI-context words that pin a "great war" / 1914-18 mention to the actual First World War
CTX = re.compile(r"\b(1914|1915|1916|1917|1918|balkans?|serbia|sarajevo|kaiser|central powers|trench|belgium|verdun|somme|marne|gallipoli|zeppelin|u-?boat|submarine warfare|entente|mobili[sz])\b", re.I)
# other/older wars that must NOT be counted as WWI leakage
OTHER = re.compile(r"\b(roses|punic|crimean|franco-?prussian|napoleon|thirty years|hundred years|of the french kings|B\.?C\.?|of 1[0-8]\d\d|of 8\d\d|of \d{1,3}\b)\b", re.I)


def is_leak(s):
    if OTHER.search(s):
        return False
    if re.search(r"\bworld war\b", s, re.I):
        return True
    if re.search(r"\bgreat war\b", s, re.I) and CTX.search(s):
        return True
    if re.search(r"\b191[4-8]\b", s) and re.search(r"\b(war|armistice|invasion|allies|central powers|treaty of versailles|revolution|bolshevik)\b", s, re.I):
        return True
    return False


MARK = re.compile(r"\b(great war|world war|191[4-8]|armistice|versailles|bolshevik)\b", re.I)


def sentences(t):
    return re.split(r"(?<=[.!?])\s+", t.replace("\n", " "))


def qtext(row):
    for k in ("chat_question", "narrative_question", "answer"):
        v = row.get(k)
        if v and str(v).strip():
            return str(v).strip()
    return ""


examples = []
for name in DATASETS:
    ds = load_dataset(f"uzh-echist-org/{name}", split="train")
    seen = set()
    for i in range(len(ds)):
        row = ds[i]
        resp = str(row.get("response") or row.get("formatted_response") or "")
        yr = row.get("year")
        for s in sentences(resp):
            if 20 < len(s) < 320 and MARK.search(s) and is_leak(s):
                key = s.lower()[:70]
                if key in seen:
                    continue
                seen.add(key)
                kind = "prediction" if PRED.search(s) else "STATED AS FACT"
                examples.append({"ds": name, "year": yr, "kind": kind, "q": qtext(row)[:180], "sentence": s.strip()})
    print(f"{name}: scanned {len(ds)} rows")

facts = [e for e in examples if e["kind"] == "STATED AS FACT"]
preds = [e for e in examples if e["kind"] == "prediction"]
facts.sort(key=lambda e: (e["year"] is None, e["year"]))
json.dump(examples, open(os.path.join(OUT, "sft_leakage_examples.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1)

rows = ""
for e in facts[:60]:
    rows += (f"<tr><td class=n>{e['year']}</td><td>{html.escape(e['q'])}</td>"
             f"<td><b>{html.escape(e['sentence'])}</b></td><td style='color:#888;font-size:.8rem'>{e['ds'].replace('ranke-1913-','')}</td></tr>")
predrows = "".join(f"<li><span style='color:#999'>[{e['year']}]</span> {html.escape(e['sentence'])}</li>" for e in preds[:20])
open(os.path.join(OUT, "sft_leakage_examples.html"), "w", encoding="utf-8").write(f"""<!doctype html><meta charset=utf-8>
<title>SFT leakage examples (Ranke-1913, self-generated)</title>
<style>body{{font:15px/1.55 Georgia,serif;max-width:1100px;margin:2rem auto;color:#1a1a1a;padding:0 1rem}}
h1{{font-size:1.4rem}} .cap{{color:#555}} table{{border-collapse:collapse;width:100%;font-size:.9rem;margin:1rem 0}}
td,th{{border:1px solid #ccc;padding:5px 9px;vertical-align:top}} .n{{text-align:right;white-space:nowrap}}
b{{color:#a11}}</style>
<h1>Post-1913 facts stated as history in the 1913 model&rsquo;s own SFT data</h1>
<p class=cap>The SFT responses were generated by <code>uzh-echist-org/Ranke-4B-1913</code> itself (self-tuning). Every
row below is that base model answering a question dated to its own era, yet asserting a post-1913 event as
established history &mdash; its pretraining contamination in plain text. {len(facts)} such sentences found (deduped);
{len(preds)} more are hedged as predictions and listed separately.</p>
<table><tr><th>yr of<br>question</th><th>the question it was answering</th><th>the leaked sentence</th><th>set</th></tr>{rows}</table>
<h2 style="font-size:1.1rem">For contrast: the same facts hedged as prediction (not leakage)</h2>
<ul style="color:#444;font-size:.9rem">{predrows}</ul>
""")

print(f"\n=== {len(facts)} sentences STATE a post-1913 event as fact (leakage); {len(preds)} hedge it as prediction.")
print("\n--- clearest leakage examples (question-year | leaked sentence): ---")
for e in facts[:16]:
    print(f"  [{e['year']}] {e['sentence'][:150]}")
print(f"\nwrote {os.path.join(OUT, 'sft_leakage_examples.html')}")
